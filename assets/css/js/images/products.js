// CATEGORY FILTER
// ===========================

categoryFilter.addEventListener("change",function(){

    let value=this.value;

    if(value==="all"){

        displayProducts(products);

    }

    else{

        let filtered=products.filter(product=>product.category===value);

        displayProducts(filtered);

    }

});